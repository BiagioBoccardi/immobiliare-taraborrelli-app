#!/usr/bin/env sh
# Writes the Netlify routing rules of the admin panel into its build folder (Netlify reads
# _redirects from the published folder). /api/v1/<service>/... is proxied to the service
# on Render, so the panel calls the API on its own address and needs no CORS.
#
#   sh scripts/netlify/admin-redirects.sh apps/admin/dist
#
# The Render addresses can be changed with AUTH_URL, LEAD_URL and PROPERTY_URL in the
# Netlify site settings (Render adds a suffix when a service name is already taken).
set -eu

OUT="${1:?build folder}"
AUTH_URL="${AUTH_URL:-https://taraborrelli-auth.onrender.com}"
LEAD_URL="${LEAD_URL:-https://taraborrelli-lead.onrender.com}"
PROPERTY_URL="${PROPERTY_URL:-https://taraborrelli-property.onrender.com}"

cat >"$OUT/_redirects" <<RULES
# Generated by scripts/netlify/admin-redirects.sh
/api/v1/auth/health      ${AUTH_URL%/}/health                     200!
/api/v1/lead/health      ${LEAD_URL%/}/health                     200!
/api/v1/property/health  ${PROPERTY_URL%/}/health                 200!
/api/v1/auth/*           ${AUTH_URL%/}/api/v1/auth/:splat         200!
/api/v1/lead/*           ${LEAD_URL%/}/api/v1/lead/:splat         200!
/api/v1/property/*       ${PROPERTY_URL%/}/api/v1/property/:splat 200!
/*                       /index.html                              200
RULES
echo "Wrote $OUT/_redirects"
